
import streamlit as st
import pandas as pd
import joblib
from pathlib import Path

# Page configuration
st.set_page_config(
    page_title="Predictive Maintenance",
    page_icon="⚙️",
    layout="wide"
)

MODEL_PATH = Path("models/best_model.pkl")

FEATURES = [
    "Engine rpm",
    "Lub oil pressure",
    "Fuel pressure",
    "Coolant pressure",
    "lub oil temp",
    "Coolant temp"
]

# Header
st.title("⚙️ Engine Predictive Maintenance")
st.write(
    "Enter engine sensor readings to obtain a prediction "
    "from the trained machine learning model."
)

st.info(
    "Enter readings in the same units and scale as the training dataset. "
    "The meaning of each predicted class must be confirmed from the "
    "dataset documentation."
)

# Check that the trained model is available
if not MODEL_PATH.exists():
    st.error(
        "The trained model was not found at models/best_model.pkl. "
        "Add the actual model generated by your successful GitHub "
        "Actions workflow before running predictions."
    )
    st.stop()

@st.cache_resource
def load_model():
    return joblib.load(MODEL_PATH)

try:
    model = load_model()
except Exception as exc:
    st.error(f"Unable to load the trained model: {exc}")
    st.stop()

st.subheader("Enter Sensor Readings")

with st.form("sensor_input_form"):
    col1, col2 = st.columns(2)

    with col1:
        engine_rpm = st.number_input(
            "Engine rpm",
            value=0.0,
            help="Enter the engine RPM reading."
        )
        lub_oil_pressure = st.number_input(
            "Lub oil pressure",
            value=0.0
        )
        fuel_pressure = st.number_input(
            "Fuel pressure",
            value=0.0
        )

    with col2:
        coolant_pressure = st.number_input(
            "Coolant pressure",
            value=0.0
        )
        lub_oil_temp = st.number_input(
            "lub oil temp",
            value=0.0
        )
        coolant_temp = st.number_input(
            "Coolant temp",
            value=0.0
        )

    submitted = st.form_submit_button(
        "Predict Engine Condition",
        type="primary"
    )

if submitted:
    input_data = pd.DataFrame(
        [[
            engine_rpm,
            lub_oil_pressure,
            fuel_pressure,
            coolant_pressure,
            lub_oil_temp,
            coolant_temp
        ]],
        columns=FEATURES
    )

    try:
        prediction = model.predict(input_data)[0]

        st.subheader("Prediction Result")
        st.success(f"Predicted Engine Condition class: {prediction}")

        st.caption(
            "This is a model classification, not a guaranteed diagnosis "
            "or a prediction of the time until engine failure."
        )

        with st.expander("View submitted sensor readings"):
            st.dataframe(input_data, use_container_width=True)

        if hasattr(model, "predict_proba"):
            probabilities = model.predict_proba(input_data)[0]

            st.write("Model class probabilities")
            probability_df = pd.DataFrame({
                "Class": model.classes_,
                "Probability": probabilities
            })
            st.dataframe(probability_df, use_container_width=True)

    except Exception as exc:
        st.error(f"Prediction failed: {exc}")
